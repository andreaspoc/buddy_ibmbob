const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('../web/node_modules/typescript');
const source = fs.readFileSync(require.resolve('../web/src/lib/officeHtmlRuntime.ts'), 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
function setup(original, values = ['Alpha', 'Beta']) {
  const listeners = [], childListeners = [], documentListeners = {}, windowEvents = {}, warnings = [];
  const stateChanges = [];
  let changed = 0, serial = 0;
  const nodes = values.map(text => ({ textContent: text, parentElement: { tagName: 'P', closest: () => null, children: [], setAttribute() {}, removeAttribute() {} } }));
  for (const node of nodes) { node.parentElement.childNodes = [node]; node.parentElement.firstChild = node; Object.defineProperty(node.parentElement, 'textContent', { get: () => node.textContent, set: value => { node.textContent = value; } }); }
  const document = { body: {}, readyState: 'complete', addEventListener(type, fn) { documentListeners[type] = fn; }, getSelection: () => ({ toString: () => '' }), createTreeWalker() { let i = 0; return { nextNode: () => nodes[i++] || null }; }, documentElement: { get outerHTML() { return JSON.stringify(nodes.map(node => node.textContent)); } } };
  const childWindow = { postMessage(data) { for (const fn of childListeners) fn({ source: parent, data }); }, addEventListener(type, fn) { if (type === 'message') childListeners.push(fn); else windowEvents[type] = fn; } };
  const parent = { postMessage(data) { if (data.type === 'warning') warnings.push(data.value); for (const fn of listeners) fn({ source: childWindow, data }); } };
  const window = { addEventListener(type, fn) { if (type === 'message') listeners.push(fn); }, removeEventListener() {}, setTimeout, clearTimeout, setInterval: fn => { window.hello = fn; return 1; }, clearInterval() {} };
  const exports = {};
  vm.runInNewContext(js, { exports, window, crypto: { randomUUID: () => 'channel-' + ++serial }, require: () => ({ useCallback: fn => fn, useEffect: fn => fn(), useMemo: fn => fn(), useRef: value => ({ current: value }), useState: initial => [initial, value => stateChanges.push(value)] }) });
  const hook = exports.useOfficeHtmlRuntime({ current: { contentWindow: childWindow } }, 'file', original, () => changed++);
  const script = hook.runtimeSource.match(/<script id="bob-office-runtime">([\s\S]*?)<\/script>/)[1];
  const childRealm = { document, parent, window: childWindow, MutationObserver: class { observe() {} }, console };
  vm.runInNewContext(script, childRealm);
  document.addSlide = text => nodes.push({ textContent: text, parentElement: { tagName: 'SECTION', closest: () => null } });
  const application = original.match(/<script data-test-app>([\s\S]*?)<\/script>/);
  if (application) vm.runInNewContext(application[1], childRealm);
  return { hook, nodes, exports, script, childListeners, parent, changed: () => changed, documentListeners, windowEvents, warnings, window, stateChanges };
}
(async () => {
  const original = '<!doctype html><html><head><script>document.write("Original application");</script></head><body><div id="app"></div></body></html>';
  const generated = setup('<html><head><script data-test-app>document.addSlide("Initialized by original script");</script></head><body></body></html>', []);
  assert.equal((await generated.hook.context()).html_nodes[0].text, 'Initialized by original script');
  const item = setup(original);
  assert(item.hook.runtimeSource.includes('<script>document.write("Original application");</script>'));
  assert.equal(await item.hook.saveSource(), original);
  const context = await item.hook.context();
  assert.equal(context.html_nodes[0].index, 1);
  const action = { type: 'html_update_text', index: 1, old_text: 'Alpha', text: '</script><script>untrusted()</script>' };
  await item.hook.apply({ version: 1, kind: 'html', actions: [action] }, context);
  assert.equal(item.nodes[0].textContent, action.text);
  assert.equal(item.changed(), 1);
  const saved = await item.hook.saveSource();
  assert(saved.startsWith(original));
  assert(saved.includes('\\u003c/script>'));
  assert(!saved.includes('<script>untrusted()'));
  assert(!saved.includes('bob-office-runtime'));
  const reloaded = setup(saved);
  assert.equal(reloaded.nodes[0].textContent, action.text);
  const savedAgain = await reloaded.hook.saveSource();
  assert.equal(savedAgain, saved);
  await assert.rejects(item.hook.apply({ kind: 'html', actions: [{ ...action, text: 'Stale' }] }, context), /changed/);
  const fresh = await item.hook.context();
  await assert.rejects(item.hook.apply({ kind: 'html', actions: [{ type: 'evil' }] }, fresh), /safely/);
  // A sibling frame with the channel still cannot issue edits.
  for (const fn of item.childListeners) fn({ source: {}, data: { bridge: 'bob-html-runtime', channel: 'channel-1', id: 'evil', command: 'apply', value: { plan: { kind: 'html', actions: [{ type: 'html_update_text', index: 2, old_text: 'Beta', text: 'ATTACK' }] }, expectedContext: fresh } } });
  assert.equal(item.nodes[1].textContent, 'Beta');
  const many = setup(original, Array.from({ length: 500 }, () => 'x'.repeat(4000)));
  const budget = await many.hook.context();
  assert.equal(budget.truncated, true);
  assert.equal(budget.text.length, 30000);
  assert(budget.html_nodes.length <= 200);
  assert(budget.html_nodes.reduce((sum, node) => sum + node.text.length, 0) <= 30000);
  const manual = setup(original);
  await manual.hook.setEditing(true);
  manual.nodes[0].textContent = 'Manual text'; manual.documentListeners.input();
  const manualSaved = await manual.hook.saveSource();
  assert.equal(setup(manualSaved).nodes[0].textContent, 'Manual text');
  manual.nodes[0].textContent = 'x'.repeat(4001); manual.documentListeners.input();
  assert.equal(manual.nodes[0].textContent, 'Manual text');
  assert(manual.warnings.some(message => message.includes('4000')));
  manual.windowEvents.error({ target: {}, message: '' });
  assert(manual.warnings.includes('A presentation resource could not load.'));
  manual.windowEvents.unhandledrejection({ reason: 'Failed dependency' });
  assert(manual.warnings.includes('Failed dependency'));
  manual.window.hello();
  assert(manual.stateChanges.includes(true));
  console.log('Office HTML runtime tests passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
