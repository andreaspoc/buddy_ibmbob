import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(new URL('../web/package.json',import.meta.url));
const ts=require('typescript');
const exports={};
new Function('exports',ts.transpileModule(fs.readFileSync('web/src/lib/communityNotifications.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText)(exports);
const {CommunityNotificationTracker}=exports;
const tracker=new CommunityNotificationTracker();
const direct={id:1,kind:'direct',name:'Bob Jones',subscribed:true,unread_count:1,latest_incoming_id:10,latest_incoming_sender_name:'Bob Jones'};
const channel={id:3,kind:'channel',name:'Design',subscribed:true,unread_count:0,latest_incoming_id:0,latest_incoming_sender_name:''};
const update=(a={},b={},viewed=null)=>tracker.update([{...direct,...a},{...channel,...b}],viewed).map(r=>r.id);
assert.deepEqual(update(),[],'Initial backlog is silent');
assert.deepEqual(update({latest_incoming_id:11}),[1],'New incoming ID alerts even when unread count stays equal');
assert.deepEqual(update({latest_incoming_id:11}),[],'Polling must not duplicate alerts');
assert.deepEqual(update({latest_incoming_id:11,unread_count:0}),[],'Read receipts stay silent');
assert.deepEqual(update({latest_incoming_id:12,unread_count:0}),[],'Own-message or already-read updates stay silent');
assert.deepEqual(update({latest_incoming_id:13},{},1),[],'Visible room stays silent');
assert.deepEqual(update({latest_incoming_id:13}),[],'Visible room advances baseline');
assert.deepEqual(update({latest_incoming_id:13},{latest_incoming_id:30,unread_count:1}),[3]);
assert.deepEqual(update({latest_incoming_id:13},{latest_incoming_id:31,unread_count:2,subscribed:false}),[],'Unsubscribed channels stay silent');
assert.deepEqual(update({latest_incoming_id:13},{latest_incoming_id:31,unread_count:2}),[],'Subscription does not replay backlog');
assert.deepEqual(update({latest_incoming_id:9},{latest_incoming_id:31,unread_count:2}),[],'Older IDs do not replay');
assert.deepEqual(tracker.update([{...direct,id:8,latest_incoming_id:50}],null).map(r=>r.id),[8],'A newly received first conversation alerts');
assert.deepEqual(tracker.update([{...direct,id:8,latest_incoming_id:50}],null),[],'A new conversation only alerts once');
console.log('PASS: notification baseline, deduplication, incoming IDs, reads, subscription and visible-room policy');
const preferences = new CommunityNotificationTracker();
preferences.update([{...direct,latest_incoming_id:100,notification_incoming_id:100}], null);
assert.deepEqual(preferences.update([{...direct,latest_incoming_id:101,notification_incoming_id:null,notification_mode:'muted'}],null),[]);
assert.deepEqual(preferences.update([{...direct,latest_incoming_id:101,notification_incoming_id:101,notification_mode:'all'}],null),[],'Unmuting does not replay');
assert.equal(preferences.update([{...direct,latest_incoming_id:103,notification_incoming_id:102,notification_mode:'mentions'}],null).length,1,'A qualifying mention is not hidden by a newer ordinary message');
assert.deepEqual(preferences.update([{...direct,latest_incoming_id:104,notification_incoming_id:104,notifications_paused:true}],null),[],'Quiet hours suppress popup');
assert.deepEqual(preferences.update([{...direct,latest_incoming_id:104,notification_incoming_id:104,notifications_paused:false}],null),[],'Quiet-hour messages do not replay');

const catchup = new CommunityNotificationTracker(true);
assert.deepEqual(catchup.update([direct, {...direct, id: 2, notification_mode: 'muted'}], null).map(room => room.id), [1], 'Login surfaces unread messages while respecting mute');
assert.deepEqual(catchup.update([direct], null), [], 'Login catch-up does not repeat on polling');
