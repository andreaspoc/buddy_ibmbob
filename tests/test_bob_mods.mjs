import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { transpile } from './frontend_transpile.mjs';
globalThis.localStorage = { store: {}, getItem(key) { return this.store[key] || null; }, setItem(key, value) { this.store[key] = String(value); } };
const source = readFileSync(new URL('../web/src/mods/registry.ts', import.meta.url), 'utf8');
const {modRegistry, BUILTIN_MODS} = await import(`data:text/javascript;base64,${Buffer.from(transpile(source)).toString('base64')}`);
assert.ok(BUILTIN_MODS.length > 0);
assert.ok(!BUILTIN_MODS.some(mod => mod.id === 'presentation-preview'), 'Studio is a core workspace');
assert.equal(modRegistry.isEnabled('live-charts'), false);
assert.equal(modRegistry.toggleMod('live-charts'), true);
assert.ok(modRegistry.getActiveCommands().some(command => command.command === '/charts'));
modRegistry.setEnabled('live-charts', false);
assert.ok(!modRegistry.getActiveCommands().some(command => command.command === '/charts'));
assert.ok(localStorage.getItem('bob_mods_enabled_states'));
const app = readFileSync(new URL('../web/src/App.tsx', import.meta.url), 'utf8');
const start = app.indexOf('    if (cleanPrompt === \'/preview\'');
const end = app.indexOf('    const modeCmd', start);
const route = new Function('cleanPrompt', 'toggleStudio', 'setModModalInitialTab', 'setIsModModalOpen', transpile('function route() {\n' + app.slice(start, end) + '\n}').replace(/^function route\(\) \{/, '').replace(/\}\s*$/, ''));
let opened = 0;
route('/preview', () => opened++, () => {}, () => {});
assert.equal(opened, 1);
let tab; let visible;
route('/mods', () => {}, value => tab = value, value => visible = value);
assert.equal(tab, 'mods'); assert.equal(visible, true);
console.log('Extension persistence and core Studio command checks passed.');
