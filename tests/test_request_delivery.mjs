import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { transpile } from './frontend_transpile.mjs';
const exports = {};
new Function('exports', transpile(readFileSync(new URL('../web/src/lib/requestDelivery.ts', import.meta.url), 'utf8'), true))(exports);
const { applyDeliveryEvent: event, localDeliveryStep: local } = exports;
let message = local({ id: 'a1' }, 'sending', new Date('2026-01-01T00:00:00Z'));
assert.equal(message.deliveryState, 'sending');
for (const [index, state] of ['accepted', 'queued', 'running', 'streaming', 'completed'].entries()) {
  const update = { type: 'delivery_state', state, timestamp: `2026-01-01T00:00:0${index + 1}Z` };
  message = event(message, update);
  assert.equal(message.deliveryState, state);
  assert.strictEqual(event(message, update), message, 'replayed state is idempotent');
}
assert.equal(message.deliveryTimeline.length, 6);
assert.equal(message.deliveryTimeline[0].source, 'local');
assert.ok(message.deliveryTimeline.slice(1).every(step => step.source === 'server'));
message = event(message, { type: 'delivery_state', state: 'queued', timestamp: '2026-01-01T00:00:01.500Z' });
assert.equal(message.deliveryState, 'completed');
assert.equal(message.deliveryTimeline[2].timestamp, '2026-01-01T00:00:01.500Z');
for (const bad of [{ type: 'delivery_state', state: 'madeup', timestamp: '2026-01-01' }, { type: 'delivery_state', state: 'running', timestamp: 'invalid' }, null]) assert.strictEqual(event(message, bad), message);
assert.equal(event({ deliveryState: 'queued' }, { type: 'start' }).deliveryState, 'queued', 'HTTP replay start is not worker execution');
const legacy = event({}, { type: 'error', cancelled: true });
assert.equal(legacy.deliveryState, 'cancelled');
assert.equal(legacy.deliveryTimeline, undefined, 'no fictional timestamps for legacy history');
assert.equal(event({}, { type: 'error', message: 'cancelled wording without flag' }).deliveryState, 'failed');
assert.equal(event({}, { type: 'done' }).deliveryState, 'completed');
const source = readFileSync(new URL('../web/src/App.tsx', import.meta.url), 'utf8');
assert.ok(source.includes("'Idempotency-Key': correlationId"));
assert.ok(source.includes('idempotency_key: correlationId'));
assert.ok(source.includes("res.headers.get('X-Idempotency-Replayed')"));
assert.ok(source.includes("userMsgId = res.headers.get('X-User-Message-Id')"));
console.log('PASS delivery transitions, authoritative timestamps, replay deduplication, legacy fallback and idempotency wiring');
const { createRequire } = await import('node:module');
const require = createRequire(new URL('../web/package.json', import.meta.url));
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const ui = {};
new Function('exports', 'require', 'React', transpile(readFileSync(new URL('../web/src/components/RequestTimeline.tsx', import.meta.url), 'utf8'), true))(ui, () => ({ t: text => text }), React);
const markup = renderToStaticMarkup(React.createElement(ui.RequestTimeline, { request: message }));
assert.ok(markup.includes('<details'));
assert.ok(markup.includes('Request timeline · Completed'));
assert.ok(markup.includes('dateTime="2026-01-01T00:00:01Z"'));
assert.ok(markup.includes('On this device'));
assert.ok(!markup.includes('a1'));
assert.equal(renderToStaticMarkup(React.createElement(ui.RequestTimeline, { request: {} })), '');
const status = renderToStaticMarkup(React.createElement(ui.DeliveryStatus, { request: { deliveryState: 'queued' } }));
assert.ok(status.includes('role="status"')); assert.ok(status.includes('Queued'));
console.log('PASS delivery status and expandable timeline render actual event times without implementation IDs');
const saving = event({deliveryState:'streaming'}, {type:'delivery_state',state:'saving',timestamp:'2026-01-01T00:01:00Z'});
assert.equal(saving.deliveryState,'saving');
assert.equal(event(saving,{type:'delta',text:'delayed chunk'}).deliveryState,'saving','Delayed text must not restart generation');
assert.equal(event(saving,{type:'done'}).deliveryState,'completed');
assert.equal(event(saving,{type:'error'}).deliveryState,'failed','Saving failure must not look completed');
console.log('PASS saving milestone, delayed text ordering, durable completion/error');
const taskExports = {};
new Function('exports','require',transpile(readFileSync(new URL('../web/src/lib/taskState.ts',import.meta.url),'utf8'),true))(taskExports, name => name.endsWith('toolName') ? {resolveToolName:name=>name} : {});
assert.equal(taskExports.answerTaskState({deliveryState:'saving',answerReadyAt:'2026-01-01T00:01:00Z',isStreaming:false,content:'Finished answer',toolsUsed:[{name:'old_tool',status:'running'}]}).label,'Completed');
assert.equal(taskExports.answerTaskState({deliveryState:'saving',isStreaming:false,content:'Finished answer'}).active,false,'Detached history must not claim a save is still active');
console.log('PASS saving status takes precedence over stale activity without inventing live history');
