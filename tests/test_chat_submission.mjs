import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { transpile } from './frontend_transpile.mjs';
const exports = {};
let requests = [], implementation;
new Function('exports', 'fetch', transpile(readFileSync(new URL('../web/src/lib/chatSubmission.ts', import.meta.url), 'utf8'), true))(exports, (...args) => { requests.push(args); return implementation(...args); });
const options = { method: 'POST', headers: { 'Idempotency-Key': 'same-request' }, body: '{"idempotency_key":"same-request"}' };
const response = { status: 200 };
implementation = async () => { if (requests.length === 1) throw new TypeError('Connection closed after server accepted'); return response; };
assert.strictEqual(await exports.submitChatRequest(options), response);
assert.equal(requests.length, 2);
assert.strictEqual(requests[0][1], requests[1][1], 'retry preserves exact body, key and message IDs');
requests = []; implementation = async () => ({ status: 409 });
assert.equal((await exports.submitChatRequest(options)).status, 409);
assert.equal(requests.length, 1, 'HTTP errors are not retried');
requests = []; const controller = new AbortController(); controller.abort();
implementation = async () => { throw new DOMException('Aborted', 'AbortError'); };
await assert.rejects(exports.submitChatRequest({ ...options, signal: controller.signal }), { name: 'AbortError' });
assert.equal(requests.length, 1);
requests = []; implementation = async () => { throw new TypeError('Offline'); };
await assert.rejects(exports.submitChatRequest(options), /Offline/);
assert.equal(requests.length, 2, 'retry is bounded');
console.log('PASS uncertain submission retries preserve idempotency and stop on HTTP errors or cancellation');
