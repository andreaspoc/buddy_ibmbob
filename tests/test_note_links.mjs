import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(new URL('../web/package.json',import.meta.url));
const ts=require('typescript');
const exports={};
new Function('exports',ts.transpileModule(fs.readFileSync('web/src/lib/noteLinks.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText)(exports);
const {extractNoteLinks,resolveNoteLinks,insertNoteLink}=exports;
const notes=[{id:1,title:'Alpha'},{id:2,title:'Duplicate'},{id:3,title:'Duplicate'}];
assert.equal(resolveNoteLinks('[[alpha]]',notes)[0].note.id,1);
assert.equal(resolveNoteLinks('[[Duplicate]]',notes)[0].ambiguous,true);
assert.equal(resolveNoteLinks('[[note:1|Name]]',[{id:1,title:'Renamed'}])[0].note.id,1);
assert.equal(resolveNoteLinks('[[Missing]]',notes)[0].note,undefined);
assert.equal(extractNoteLinks('`[[Alpha]]`\n```text\n[[Alpha]]\n```\n[[Alpha]]').length,1);
assert.equal(extractNoteLinks('\\[[Alpha]] [[note:no]]').length,0);
assert.equal(insertNoteLink({id:1,title:'[bad]\nname'}),'[[note:1|bad  name]]');
assert.throws(()=>insertNoteLink({id:'bad',title:'Title'}));
const link=extractNoteLinks('a [[Alpha]] b')[0];assert.equal(link.start,2);assert.equal(link.end,11);
console.log('Note link parsing, stable IDs, ambiguity and code checks passed');
