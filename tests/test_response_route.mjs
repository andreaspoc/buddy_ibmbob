import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { transpile } from './frontend_transpile.mjs';
const exports = {};
new Function('exports', transpile(readFileSync(new URL('../web/src/lib/responseRoute.ts', import.meta.url), 'utf8'), true))(exports);
const { matchesResponseRoute: matches, acceptArtifactRevision: accept } = exports;
const route = { workspaceId: 'chat1', jobId: 'job1', correlationId: 'trace1', userMessageId: 'u1', assistantMessageId: 'a1' };
const event = { workspace_id: 'chat1', chat_id: 'chat1', job_id: 'job1', correlation_id: 'trace1', user_message_id: 'u1', assistant_message_id: 'a1', session_id: 'model-context-unrelated-to-chat' };
assert.ok(matches(event, route));
for (const key of ['workspace_id', 'chat_id', 'job_id', 'correlation_id', 'user_message_id', 'assistant_message_id']) assert.equal(matches({ ...event, [key]: 'other' }, route), false, key);
for (const bad of [null, false, [], 'event']) assert.equal(matches(bad, route), false);
assert.ok(matches({ type: 'delta', text: 'Legacy history' }, route));
const versions = new Map();
assert.ok(accept(versions, 'chat1/job1/a.html', 10));
assert.equal(accept(versions, 'chat1/job1/a.html', 9), false);
assert.equal(accept(versions, 'chat1/job1/a.html', 10), false);
assert.equal(accept(versions, 'chat1/job1/a.html', undefined), false);
assert.ok(accept(versions, 'chat1/job1/a.html', 11));
assert.ok(accept(versions, 'chat1/job1/b.html', 5));
assert.ok(accept(versions, 'chat1/job2/a.html', 1));
const source = readFileSync(new URL('../web/src/App.tsx', import.meta.url), 'utf8');
assert.ok(source.includes('correlation_id: correlationId, user_message_id: userMsgId, assistant_message_id: assistantMsgId'));
assert.ok(source.includes('!isCurrentRequest() || !matchesResponseRoute(event,'));
assert.ok(source.includes('id: evt.user_message_id || evt.message_id'));
assert.ok(source.includes('id: evt.assistant_message_id'));
console.log('PASS chat response correlation routing, model context separation, stable history IDs, artifact ordering');
