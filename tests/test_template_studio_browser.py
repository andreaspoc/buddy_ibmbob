"""Real Chromium verification with explicitly synthetic template network responses.

Serve tests via clarification_vite.config.mjs; set TEMPLATE_STUDIO_FIXTURE_URL
when Chromium runs in Docker. Downloads are generated by the real exporters.
"""
import asyncio
import json
import os
import zipfile
from pathlib import Path
from playwright.async_api import async_playwright

async def main():
    async with async_playwright() as runtime:
        browser=await runtime.chromium.launch(executable_path=os.getenv('CHROMIUM_PATH','/usr/bin/chromium'),args=['--no-sandbox'])
        page=await browser.new_page(viewport={'width':1280,'height':1000},accept_downloads=True)
        errors=[]
        page.on('pageerror',lambda error:errors.append(str(error)))
        await page.goto(os.getenv('TEMPLATE_STUDIO_FIXTURE_URL','http://127.0.0.1:3002/template_studio_fixture.html'))
        save=page.get_by_role('button',name='Save template',exact=True)
        await save.wait_for()
        for width in [1280,390,320]:
            await page.set_viewport_size({'width':width,'height':1000})
            await page.evaluate('document.fonts.ready')
            assert await page.evaluate('document.documentElement.scrollWidth <= innerWidth'),f'Overflow at {width}px'
            assert await page.locator('.template-studio-colors input[type=color]').first.evaluate('node=>getComputedStyle(node).width') == '36px'
            assert await page.locator('.template-studio-controls fieldset label').first.evaluate('node=>getComputedStyle(node).flexDirection') == 'column'
            await page.screenshot(path=f'/tmp/template-studio-{width}.png', full_page=True)
            await page.get_by_label('Primary hex',exact=True).scroll_into_view_if_needed()
            await page.screenshot(path=f'/tmp/template-studio-controls-{width}.png',full_page=True)
        await page.get_by_label('Start from',exact=True).select_option('synthetic-starter')
        await page.wait_for_function("document.querySelector('[aria-label=\"Template name\"]').value === 'Synthetic starter copy'")
        assert await page.get_by_label('Brand',exact=True).input_value()=='Synthetic brand'
        assert await page.get_by_label('Card shape',exact=True).input_value()=='ellipse'
        assert await page.get_by_label('Decoration',exact=True).input_value()=='sidebar'
        assert await page.get_by_label('Border width',exact=True).input_value()=='3'
        ask=page.get_by_role('button',name='Ask Bob to design',exact=True)
        assert await ask.is_disabled()
        await page.get_by_label('Describe your template').fill('An emerald template with ellipse cards')
        await ask.click()
        assert await page.evaluate('window.fixtureState.briefs')==['An emerald template with ellipse cards']
        await page.get_by_role('button',name='Refresh drafts',exact=True).click()
        await page.get_by_label('Bob draft',exact=True).select_option('synthetic.bobtemplate.json')
        await page.get_by_role('button',name='Load Bob draft',exact=True).click()
        assert await page.get_by_label('Template name',exact=True).input_value()=='Synthetic Bob draft'
        await page.get_by_label('Template name',exact=True).fill('')
        assert await save.is_disabled()
        await page.get_by_label('Template name',exact=True).fill('Synthetic emerald template')
        await page.get_by_label('Brand',exact=True).fill('Synthetic brand')
        await page.get_by_label('Primary hex',exact=True).fill('#137A52')
        await page.get_by_label('Primary hex',exact=True).blur()
        assert await page.get_by_role('img',name='Title slide preview').locator('svg').count()==1
        assert '#137a52' in (await page.get_by_role('img',name='Title slide preview').inner_html()).lower()
        await page.get_by_role('tab',name='Content slide',exact=True).click()
        await page.get_by_label('Card shape',exact=True).select_option('ellipse')
        await page.get_by_label('Decoration',exact=True).select_option('sidebar')
        assert await page.get_by_role('img',name='Content slide preview').locator('ellipse').count()>0
        await page.get_by_label('Primary hex',exact=True).fill('invalid')
        assert await save.is_disabled()
        await page.get_by_label('Primary hex',exact=True).fill('#137A52')
        assert await save.is_enabled()
        await save.click()
        await page.get_by_text('Synthetic save failure: please retry',exact=False).wait_for()
        assert await save.is_enabled()
        await page.evaluate('window.fixtureState.failSave=false')
        for layout, expected in [('comparison', 'Option A'), ('timeline', 'Stage 1')]:
            await page.get_by_label('Content layout',exact=True).select_option(layout)
            assert expected in await page.get_by_role('img',name='Content slide preview').text_content()
        for chart in ['bar','line','doughnut']:
            await page.get_by_label('Chart style',exact=True).select_option(chart)
            await page.get_by_role('tab',name='Chart slide',exact=True).click()
            assert 'Illustrative sample values' in await page.get_by_role('img',name='Chart slide preview').text_content()
        preview=page.get_by_role('img',name='Chart slide preview')
        assert await preview.locator('title').filter(has_text='A: 25').count() >= 1
        fills=await preview.locator('path').evaluate_all('(nodes)=>nodes.map(node=>node.getAttribute("fill")).filter(Boolean)')
        assert len(set(fills)) >= 3, fills
        async with page.expect_download() as pending:
            await page.get_by_role('button',name='Download PowerPoint',exact=True).click()
        download=await pending.value
        await download.save_as('/tmp/template-doughnut.pptx')
        with zipfile.ZipFile('/tmp/template-doughnut.pptx') as archive:
            charts=[name for name in archive.namelist() if name.startswith('ppt/charts/chart') and name.endswith('.xml')]
            chart_xml=archive.read(charts[0]).decode()
            assert 'doughnutChart' in chart_xml and '<c:legend' in chart_xml
            import re
            chart_colors=set(re.findall(r'<a:srgbClr val="([A-Fa-f0-9]{6})"',chart_xml))
            assert len(chart_colors) >= 3, chart_colors
        await page.get_by_label('Chart style',exact=True).select_option('bar')
        await page.get_by_label('HTML slide transition',exact=True).select_option('slide')
        for label,suffix in [('Download HTML','.html'),('Download PowerPoint','.pptx')]:
            async with page.expect_download() as pending:
                await page.get_by_role('button',name=label,exact=True).click()
            download=await pending.value
            assert download.suggested_filename.endswith(suffix)
            path=Path('/tmp/template-studio-export'+suffix)
            await download.save_as(str(path))
            if suffix=='.pptx':
                with zipfile.ZipFile(path) as archive:
                    slides=[name for name in archive.namelist() if name.startswith('ppt/slides/slide') and name.endswith('.xml')]
                    assert len(slides)==4
                    charts=[name for name in archive.namelist() if name.startswith('ppt/charts/chart') and name.endswith('.xml')]
                    assert charts and 'barChart' in archive.read(charts[0]).decode()
                    text=''.join(archive.read(name).decode() for name in slides)
                    assert '137A52' in text and 'ellipse' in text and 'Illustrative sample values' in text
            else:
                text=path.read_text()
                assert '137a52' in text.lower() and '<html' in text.lower()
                exported=await browser.new_page()
                await exported.set_content(text)
                assert await exported.locator('#position').text_content()=='1 / 4'
                assert await exported.locator('main section:not([hidden])').evaluate('node=>getComputedStyle(node).animationName')=='templateSlide'
                await exported.emulate_media(reduced_motion='reduce')
                assert await exported.locator('main section:not([hidden])').evaluate('node=>getComputedStyle(node).animationName')=='none'
                await exported.get_by_role('button',name='Next',exact=True).click()
                assert await exported.locator('#position').text_content()=='2 / 4'
                await exported.keyboard.press('End')
                assert await exported.locator('#position').text_content()=='4 / 4'
                await exported.keyboard.press('Home')
                assert await exported.locator('#position').text_content()=='1 / 4'
                await exported.close()
        await page.get_by_label('HTML slide navigation',exact=True).uncheck()
        async with page.expect_download() as pending:
            await page.get_by_role('button',name='Download HTML',exact=True).click()
        download=await pending.value
        await download.save_as('/tmp/template-static.html')
        static=Path('/tmp/template-static.html').read_text()
        assert 'id="next"' not in static and 'ArrowRight' not in static
        await page.get_by_label('HTML slide navigation',exact=True).check()
        await save.click()
        await page.get_by_role('button',name='Create presentation',exact=True).wait_for()
        payload=await page.evaluate('window.fixtureState.requests.at(-1)')
        assert payload['colors']['primary']=='#137A52'
        assert payload['design']['shape']=='ellipse' and payload['design']['decoration']=='sidebar'
        for label,format_name in [('Interactive HTML','html'),('PowerPoint','pptx')]:
            await page.get_by_role('radio',name=label,exact=True).check()
            await page.get_by_role('button',name='Create presentation',exact=True).click()
            result=await page.evaluate('window.fixtureState.confirmed.at(-1)')
            assert result=={'format':format_name,'selected':'custom-fixture-theme'}
        await page.screenshot(path='/tmp/bob-template-studio-mobile.png',full_page=True)
        assert not errors,'\n'.join(errors)
        print(json.dumps({'passed':'desktop/mobile layout and color field sizing; palette; comparison/timeline; chart preview; validation; save retry; actual 4-slide native-chart PPTX; HTML button/keyboard navigation and static option; saved template selection','pageErrors':errors}))
        await browser.close()

asyncio.run(main())
